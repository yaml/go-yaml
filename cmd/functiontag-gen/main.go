// functiontag-gen generates a portable export map for a Go package.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"go/importer"
	"go/token"
	"go/types"
	"io"
	"os"
	"os/exec"
	"sort"
	"strings"
)

type listedPackage struct {
	ImportPath, Name, Export string
	Error                    *struct{ Err string }
}

func generate(importPath, packageName, name, symbols string) ([]byte, error) {
	command := exec.Command("go", "list", "-deps", "-export", "-json", importPath)
	var stderr bytes.Buffer
	command.Stderr = &stderr
	output, err := command.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w: %s", err, &stderr)
	}
	packages := map[string]listedPackage{}
	var selected listedPackage
	decoder := json.NewDecoder(bytes.NewReader(output))
	for {
		var pkg listedPackage
		if err := decoder.Decode(&pkg); err == io.EOF {
			break
		} else if err != nil {
			return nil, err
		}
		if pkg.Error != nil {
			return nil, fmt.Errorf("package %s: %s", pkg.ImportPath, pkg.Error.Err)
		}
		packages[pkg.ImportPath] = pkg
		selected = pkg
	}
	lookup := func(path string) (io.ReadCloser, error) { return os.Open(packages[path].Export) }
	imported, err := importer.ForCompiler(token.NewFileSet(), "gc", lookup).Import(selected.ImportPath)
	if err != nil {
		return nil, err
	}
	requested := map[string]bool{}
	if symbols != "" {
		for _, symbol := range strings.Split(symbols, ",") {
			requested[symbol] = true
		}
	}
	var exports []string
	for _, symbol := range imported.Scope().Names() {
		if len(requested) > 0 && !requested[symbol] {
			continue
		}
		function, ok := imported.Scope().Lookup(symbol).(*types.Func)
		reason := "not an exported function"
		supported := ok && function.Exported()
		if supported {
			signature := function.Type().(*types.Signature)
			supported = signature.TypeParams() == nil || signature.TypeParams().Len() == 0
			if !supported {
				reason = "generic function requires an explicit instantiation"
			}
			returns := signature.Results()
			if returns.Len() > 2 || (returns.Len() == 2 && !types.Identical(returns.At(1).Type(), types.Universe.Lookup("error").Type())) {
				supported = false
				reason = "unsupported return signature"
			}
		}
		if !supported {
			if len(requested) > 0 {
				return nil, fmt.Errorf("%s: %s", symbol, reason)
			}
			if ok && function.Exported() {
				fmt.Fprintf(os.Stderr, "Skipping %s: %s\n", symbol, reason)
			}
			continue
		}
		exports = append(exports, symbol)
		delete(requested, symbol)
	}
	if len(requested) > 0 {
		missing := []string{}
		for symbol := range requested {
			missing = append(missing, symbol)
		}
		sort.Strings(missing)
		return nil, fmt.Errorf("unknown symbols: %s", strings.Join(missing, ", "))
	}
	if len(exports) == 0 {
		return nil, fmt.Errorf("no supported exported functions in %s", importPath)
	}
	var source bytes.Buffer
	fmt.Fprintf(&source, "// Code generated by functiontag-gen. DO NOT EDIT.\n\npackage %s\n\nimport library %q\n\nvar %s = map[string]any{\n", packageName, selected.ImportPath, name)
	for _, symbol := range exports {
		fmt.Fprintf(&source, "%q: library.%s,\n", symbol, symbol)
	}
	source.WriteString("}\n")
	return format.Source(source.Bytes())
}

func main() {
	library := flag.String("import", "", "Go package import path")
	packageName := flag.String("package", "main", "package for generated source")
	name := flag.String("name", "Functions", "export map variable name")
	output := flag.String("o", "", "output file (stdout when omitted)")
	symbols := flag.String("symbols", "", "optional comma-separated function names")
	flag.Parse()
	if *library == "" {
		fmt.Fprintln(os.Stderr, "-import is required")
		os.Exit(2)
	}
	data, err := generate(*library, *packageName, *name, *symbols)
	if err == nil {
		if *output == "" {
			_, err = os.Stdout.Write(data)
		} else {
			err = os.WriteFile(*output, data, 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
